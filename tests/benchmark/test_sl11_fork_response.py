def test_version_registration():
    from AG3S.adapters.panda import profile as pf

    assert pf.LSFORK_VERSIONS[0] == NEW and all(v.endswith("-lsfork") for v in pf.LSFORK_VERSIONS) and NEW in pf.AG3S_VERSIONS and pf.LSFORK_FLAGS == ("--response-model", "libero_safety_fork")
    assert list(pf.AG3S_VERSIONS[NEW]) == list(pf.AG3S_VERSIONS[PC]) + list(pf.LSFORK_FLAGS)
    assert not any("--response-model" in f for n, f in pf.AG3S_VERSIONS.items() if n not in pf.LSFORK_VERSIONS + pf.SOTA_LSNATIVE_VERSIONS)
    assert pf.is_final_version(NEW) and pf._lsfork_base(NEW) == PC and pf._lsfork_base(PC) == PC
    assert pf.version_server_argv(NEW) == pf.version_server_argv(PC)
    assert pf.version_server_flags(NEW)[-2:] == ["--hsr6-probe", pf.PANDA_HSR6_PROBE]                # pc: takes the probe
    assert pf.version_server_flags(NEW)[:-4] == pf.version_server_flags(PC)[:-2]
    assert pf.version_server_flags(NEW)[-4:-2] == list(pf.LSFORK_FLAGS)


def test_register_lsfork_is_generic_and_idempotent():
    from AG3S.adapters.panda import profile as pf

    before = dict(pf.AG3S_VERSIONS)
    n_before = pf.LSFORK_VERSIONS
    try:
        name = pf.register_lsfork("AG3S-final-panda-v3-e0to-pc-surface")
        assert name == "AG3S-final-panda-v3-e0to-pc-surface-lsfork" and pf.is_final_version(name)
        assert pf.register_lsfork("AG3S-final-panda-v3-e0to-pc-surface") == name and pf.LSFORK_VERSIONS.count(name) == 1
        with pytest.raises(ValueError):
            pf.register_lsfork(NEW)
        with pytest.raises(ValueError):
            pf.register_lsfork("not-a-version")
    finally:
        for k in set(pf.AG3S_VERSIONS) - set(before):
            del pf.AG3S_VERSIONS[k]
        pf.LSFORK_VERSIONS = n_before


def test_option_parses_and_only_it_differs(gpu_ok, monkeypatch):
    from AG3S.adapters.panda import profile as pf
    from AG3S.adapters.panda import server as ps
    from AG3S.trajopt import serve_safe as ss

    _probe_or_skip()
    a, b = _args(NEW, monkeypatch), _args(PC, monkeypatch)
    assert a.response_model == "libero_safety_fork" and b.response_model == "robosuite141"
    assert {k for k in vars(a) if vars(a)[k] != vars(b)[k]} == {"response_model"}
    assert "response_model" not in ps.UNPORTED_FINAL_CONFIG_DESTS
    ps.check_unported_flags(a, None)
    ss.reject_panda_only_flags(ss.build_parser(), a)
    assert pf.match_ag3s_version(a) == NEW and pf.match_ag3s_version(b) == PC
    va, vb = pf.version_flag_values(a), pf.version_flag_values(b)
    assert va["response_model"] == "libero_safety_fork" and "response_model" not in vb      # older records keep their keys
    assert set(vb) <= set(va) and all(va[k] == vb[k] for k in vb)
    for v in (PC, f"{PC}-surface", f"{PC}-uncwaive", "AG3S-final-panda-v3-e0to", "V11AB-pb7"):
        assert "response_model" not in pf.version_flag_values(_args(v, monkeypatch)), v


