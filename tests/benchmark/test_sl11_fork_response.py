def _chunk(seed=3, scale=0.4):
    return np.clip(np.random.default_rng(seed).normal(0, scale, (10, 7)), -1, 1)


# ------------------------------------------------------------------------------------------------ (a) default unchanged
def test_default_is_bit_identical(kin):
    from AG3S.adapters.panda import action as pa

    A = _chunk()
    prev = (np.full(3, 0.002), np.full(3, 0.01))
    c0 = pa.delta_chunk_to_joint_chunk(kin, A, Q0, np.eye(4), prev_step_world=prev)
    c1 = pa.delta_chunk_to_joint_chunk(kin, A, Q0, np.eye(4), prev_step_world=prev, response=pa.RESPONSE)
    c2 = pa.delta_chunk_to_joint_chunk(kin, A, Q0, np.eye(4), prev_step_world=prev, response=pa.response_for("robosuite141"))
    assert c0.response is None and c2.response is None
    assert np.array_equal(c0.joint_chunk, c1.joint_chunk) and np.array_equal(c0.joint_chunk, c2.joint_chunk)
    ref = c0.joint_chunk.astype(np.float32)
    mod = ref.copy()
    mod[3:, 1] += 0.004
    for mode in ("A", "B", "C"):
        o0, r0 = pa.joint_chunk_to_delta_chunk(kin, c0, mod, ref, mode=mode)
        o1, r1 = pa.joint_chunk_to_delta_chunk(kin, c1, mod, ref, mode=mode, response=pa.RESPONSE)
        assert np.array_equal(o0, o1) and r0 == r1
    assert np.array_equal(pa.predict_ee_path(kin, c0, A), pa.predict_ee_path(kin, c1, A, pa.RESPONSE))
    b0 = pa.action_box_from_conversion(c0, margin=0.05, n_rows=5)
    b1 = pa.action_box_from_conversion(c1, margin=0.05, n_rows=5, response=pa.RESPONSE)
    assert np.array_equal(b0.alpha, b1.alpha) and np.array_equal(b0.beta, b1.beta)


