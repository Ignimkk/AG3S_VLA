# ------------------------------------------------------------------------------------------------ (b) the fit file
def test_fork_fit_file_and_unit_mapping():
    import libero_safety_client as lsc
    from AG3S.adapters.panda import action as pa
    from AG3S.adapters.panda import fit_response as fr

    fit = json.loads(FORK_JSON.read_text())
    assert fit["pos"]["r2"] >= 0.9 and fit["rot"]["r2"] >= 0.9                       # task §2 offline gate
    for g in ("pos", "rot"):
        assert {"alpha", "beta", "r2", "n", "rmse", "steady_state_gain"} <= set(fit[g])
        assert fit[g]["steady_state_gain"] == pytest.approx(fit[g]["beta"] / (1 - fit[g]["alpha"]))
        assert 0.0 < fit[g]["alpha"] < 1.0 and 0.5 < fit[g]["steady_state_gain"] < 1.5      # the fork's gain is ~1
    assert "fit_response.py" in fit["provenance"]["script"] and (ROOT / "AG3S/adapters/panda/fit_response.py").exists()
    # the gains are the client's libero_to_safety (REALISED_GAIN of 1.4.1 / fork)
    src, dst = lsc.REALISED_GAIN["robosuite_1.4.1"], lsc.REALISED_GAIN["libero_safety_fork"]
    gains = fit["libero_scale"]["gains_libero_to_safety"]
    assert gains["pos"] == pytest.approx(src["pos"] / dst["pos"], rel=1e-12) == pytest.approx(fr.GAINS_LIBERO_TO_SAFETY["pos"])
    assert gains["rot"] == pytest.approx(src["ori"] / dst["ori"], rel=1e-12) == pytest.approx(fr.GAINS_LIBERO_TO_SAFETY["rot"])
    a = lsc.adapt_action(np.ones(7), "libero_to_safety")
    assert a[0] == pytest.approx(gains["pos"]) and a[3] == pytest.approx(gains["rot"])
    # loader: beta_server = beta_fork * gain / scale, alpha unchanged
    m = pa.response_for("libero_safety_fork")
    assert m["variant"] == "libero_safety_fork" and m["path"] == str(FORK_JSON)
    assert m["pos"] == pytest.approx((fit["pos"]["alpha"], fit["pos"]["beta"] * gains["pos"] / pa.OSC_POS_SCALE))
    assert m["rot"] == pytest.approx((fit["rot"]["alpha"], fit["rot"]["beta"] * gains["rot"] / pa.OSC_ORI_SCALE))
    assert m["pos"] != pa.RESPONSE["pos"] and m["rot"] != pa.RESPONSE["rot"]


def test_fit_recovers_a_known_plant(tmp_path):
    """fit_response on synthetic episodes generated by a known (alpha, beta) returns them."""
    from AG3S.adapters.panda import fit_response as fr

    rng = np.random.default_rng(0)
    al, be = 0.6, 0.3
    files = []
    for i in range(3):
        T = 200
        a = np.zeros((T, 7))
        a[:, :6] = np.clip(np.cumsum(rng.normal(0, 0.1, (T, 6)), 0) * 0.2 + rng.normal(0, 0.2, (T, 6)), -1, 1)
        p = np.zeros((T + 1, 3))
        y = np.zeros(3)
        for t in range(T):
            y = al * y + be * fr.GAINS_LIBERO_TO_SAFETY["pos"] * a[t, :3]
            p[t + 1] = p[t] + y
        q = np.tile([0.0, 0.0, 0.0, 1.0], (T + 1, 1))
        f = tmp_path / f"e{i}.npz"
        np.savez(f, obs_robot0_eef_pos=p, obs_robot0_eef_quat=q, action=a, is_wait=np.zeros(T, bool))
        files.append(str(f))
    res = fr.fit_group(files, "pos", fr.GAINS_LIBERO_TO_SAFETY["pos"])
    assert res["alpha"] == pytest.approx(al, abs=1e-6) and res["beta"] == pytest.approx(be, abs=1e-6)
    assert res["r2"] > 0.999999 and res["trim"]["dropped_fraction"] < 0.05


# ------------------------------------------------------------------------------------------------ (c) step response
def _fork_plant_path(a_server, fit, p0_steps=None):
    """EE displacement path of the fork plant (native alpha / beta, x = gains x server action), world frame, zero start step."""
    g = fit["libero_scale"]["gains_libero_to_safety"]
    yp = np.zeros(3)
    yr = np.zeros(3)
    P, Rv = [], []
    cp = np.zeros(3)
    cr = np.zeros(3)
    for a in np.clip(np.asarray(a_server, np.float64), -1, 1):
        yp = fit["pos"]["alpha"] * yp + fit["pos"]["beta"] * g["pos"] * a[:3]
        yr = fit["rot"]["alpha"] * yr + fit["rot"]["beta"] * g["rot"] * a[3:6]
        cp, cr = cp + yp, cr + yr
        P.append(cp.copy())
        Rv.append(cr.copy())
    return np.array(P), np.array(Rv)


def _case(kin, model):
    from AG3S.adapters.panda import action as pa

    A = np.zeros((10, 7))
    A[:, :6] = [0.3, 0.1, -0.2, 0.0, 0.02, 0.01]
    conv = pa.delta_chunk_to_joint_chunk(kin, A, Q0, np.eye(4), response=pa.response_for(model))
    ref = conv.joint_chunk.copy()
    mod = ref.copy()
    mod[3:, 1] += 0.004                                     # refined path leaves the reference at row 3 (small: no clipping)
    mod[3:, 3] += 0.002
    return pa, A, conv, ref, mod


def test_inverse_realises_the_refined_path_on_the_fork_plant(kin):
    fit = json.loads(FORK_JSON.read_text())
    pa, A, conv, ref, mod = _case(kin, "libero_safety_fork")
    assert conv.response is not None
    out, rec = pa.joint_chunk_to_delta_chunk(kin, conv, mod, ref, mode="C")
    assert not rec["saturated_rows"] and rec["corrected_rows"]
    # what the refined chain wants, relative to the reference chain: FK(refined_k) - FK(reference_k) (world = base frame here)
    want_p = np.array([kin.fk(mod[k, :7])[0] - kin.fk(ref[k, :7])[0] for k in range(10)])
    Pa, _ = _fork_plant_path(A, fit)
    Po, _ = _fork_plant_path(out, fit)
    got_p = Po - Pa
    assert np.abs(want_p).max() > 1e-3
    assert np.abs(got_p - want_p).max() < 2e-5          # < 0.02 mm on a change of several mm
    # the default model's inverse does not land there on the fork plant
    pa, A2, conv2, ref2, mod2 = _case(kin, "robosuite141")
    out2, _ = pa.joint_chunk_to_delta_chunk(kin, conv2, mod2, ref2, mode="C")
    got2 = _fork_plant_path(out2, fit)[0] - Pa
    assert np.abs(got2 - want_p).max() > 5 * np.abs(got_p - want_p).max()


def test_inverse_realises_the_refined_rotation_on_the_fork_plant(kin):
    fit = json.loads(FORK_JSON.read_text())
    pa, A, conv, ref, mod = _case(kin, "libero_safety_fork")
    out, _ = pa.joint_chunk_to_delta_chunk(kin, conv, mod, ref, mode="C")
    want, prev_s, prev_r = [], None, None
    cum = np.zeros(3)
    fs, fr_ = [kin.fk(Q0)], [kin.fk(Q0)]
    for k in range(10):
        fs.append(kin.fk(mod[k, :7]))
        fr_.append(kin.fk(ref[k, :7]))
        ds = pa.matrix_to_rotvec(fs[-1][1] @ fs[-2][1].T) - pa.matrix_to_rotvec(fr_[-1][1] @ fr_[-2][1].T)
        cum = cum + ds
        want.append(cum.copy())
    want = np.array(want)
    got = _fork_plant_path(out, fit)[1] - _fork_plant_path(A, fit)[1]
    assert np.abs(want).max() > 1e-3 and np.abs(got - want).max() < 2e-5


def test_forward_prediction_matches_the_fork_plant(kin):
    """Forward: the IK targets follow the fork plant's EE path for the policy chunk (so reference = what the fork does)."""
    fit = json.loads(FORK_JSON.read_text())
    from AG3S.adapters.panda import action as pa

    A = _chunk(seed=5, scale=0.5)
    conv = pa.delta_chunk_to_joint_chunk(kin, A, Q0, np.eye(4), response=pa.response_for("libero_safety_fork"))
    P, _ = _fork_plant_path(A, fit)
    p0 = kin.fk(Q0)[0]
    pred = np.array([t[0] for t in conv.targets_base]) - p0
    assert np.abs(pred - P).max() < 1e-12
    pa_pred = pa.predict_ee_path(kin, conv, A) - p0                 # follows conv.response
    assert np.abs(pa_pred - P).max() < 1e-12


