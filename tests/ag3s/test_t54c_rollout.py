"""T54c rollout launcher template (`t54c_rollout.write_rollout_p`): generated from the T53 run's ``p/`` (read
only) into a temporary run; ports 8292 · 8293, the given episodes and seeds, no trace of the T53 run path."""

from __future__ import annotations

import json
import pathlib
import subprocess

import pytest

from AG3S.ag3s.experiments.studies import t54c_records as reg
from AG3S.ag3s.experiments.studies import t54c_rollout as G

T53_P = pathlib.Path("/mnt/dev/AG3S_VLA-storage/results/development/"
                     "20261013T100210+0900_4a540f1a18d7_cb037c425d2f/verify/T53/p")
#: a synthetic registry (slot s -> episode 1900 + s), so the test does not depend on the frozen table
EXP = {1900 + s: ("apple", "left" if s % 3 == 0 else "right", s, f"Put the apple in the basket.")
       for s in range(16)}

needs_t53 = pytest.mark.skipif(not (T53_P / "env.sh").is_file(), reason="T53 run p/ not available")


@needs_t53
def test_generated_launcher(tmp_path):
    run = tmp_path / "run"
    rec = G.write_rollout_p(T53_P, run, expected=EXP, check_storage=False)
    p = run / "verify" / "T54c" / "p"
    names = {f.name for f in p.iterdir()}
    assert {"env.sh", "run_chain.sh", "run_client.sh", "start_server.sh", "launch_t54c.sh",
            "make_snapshot.sh", "md5_files.sh", "check_run.py", "update_partial.py",
            "GENERATED.json"} <= names
    assert not names & {"launch_t53.sh", "launch_all.sh", "launch_cl.sh", "build_verify_t53.py",
                        "fig_t53.py", "code_md5_t53.txt"}
    old = rec["old_run"]
    for f in p.iterdir():
        if f.is_file() and f.name != "GENERATED.json":
            t = "\n".join(ln for ln in f.read_text().splitlines()
                          if not ln.startswith("# T54c: generated by"))   # provenance header names the source
            assert old not in t, f.name
            if f.suffix == ".sh":
                assert "T53_GPU_LOCK_HELD" not in t, f.name
    env = (p / "env.sh").read_text()
    assert f"RUN={run}" in env and "V=$RUN/verify/T54c" in env
    assert 'port_ok() { [ "$1" = 8292 ] || [ "$1" = 8293 ]; }' in env
    left = sorted(str(e) for e, v in EXP.items() if v[1] == "left")
    assert f"{'|'.join(left)}) echo left;;" in env
    assert "seed_of() { echo $(( $1 * 10 + 1 )); }" in env
    launch = (p / "launch_t54c.sh").read_text()
    even = " ".join(str(1900 + s) for s in range(0, 16, 2))
    odd = " ".join(str(1900 + s) for s in range(1, 16, 2))
    assert f"for e in {even}; do" in launch and f"for e in {odd}; do" in launch
    assert "8290" not in launch and "8291" not in launch and "--port 829[23]" in launch
    assert "T54C_GPU_LOCK_HELD=1" in launch
    chain = (p / "run_chain.sh").read_text()
    assert chain.count("code_md5_t54c.txt") == 3 and "(8292 / 8293 only)" in chain
    assert '"step": "T54c"' in (p / "update_partial.py").read_text()
    seeds = json.loads((run / "verify" / "T54c" / "seeds.json").read_text())["episodes"]
    assert [x["episode"] for x in seeds] == [1900 + s for s in range(16)]
    assert [x["port"] for x in seeds] == [8292, 8293] * 8
    assert all(x["seed"] == x["episode"] * 10 + 1 for x in seeds)
    snap = (p / "make_snapshot.sh").read_text()
    assert G.BASE_HEAD in snap and "git archive" in snap and "never overwritten" in snap
    for f in ("env.sh", "run_chain.sh", "launch_t54c.sh", "make_snapshot.sh", "md5_files.sh",
              "run_client.sh", "start_server.sh"):
        assert subprocess.run(["bash", "-n", str(p / f)]).returncode == 0, f
    # the env sources cleanly and answers for the new episodes / ports only
    out = subprocess.run(["bash", "-c", f"source {p}/env.sh; side_of 1900; side_of 1901; side_of 1840; "
                                        "port_ok 8292 && echo ok92; port_ok 8290 || echo no90"],
                         capture_output=True, text=True)
    assert out.stdout.split() == ["left", "right", "BADEP", "ok92", "no90"]
    gen = json.loads((p / "GENERATED.json").read_text())
    assert gen["files"]["env.sh"]["substitutions"]["port_ok"] == 1
    # never overwritten
    with pytest.raises(SystemExit):
        G.write_rollout_p(T53_P, run, expected=EXP, check_storage=False)


@needs_t53
def test_refuses_the_t53_run_and_a_wrong_registry(tmp_path):
    with pytest.raises(SystemExit):
        G.write_rollout_p(T53_P, T53_P.parents[2], expected=EXP, check_storage=False)
    with pytest.raises(SystemExit):
        G.write_rollout_p(T53_P, tmp_path / "r", expected=dict(list(EXP.items())[:15]), check_storage=False)


def test_refuses_a_changed_source(tmp_path):
    src = tmp_path / "p"
    src.mkdir()
    (src / "env.sh").write_text("RUN=/old/run\nV=$RUN/verify/T53\nside_of() { x; }\n")  # no port_ok line
    (src / "launch_t53.sh").write_text("#!/bin/bash\n")
    with pytest.raises(SystemExit, match="port_ok"):
        G.write_rollout_p(src, tmp_path / "run", expected=EXP, check_storage=False)


def test_side_of_line_and_port_lists():
    line = G.side_of_line({1: ("a", "left", 0, ""), 2: ("a", "right", 1, ""), 3: ("a", "left", 2, "")})
    assert line.startswith("side_of() { case $1 in 1|3) echo left;; 2) echo right;;")
    with pytest.raises(SystemExit):
        G.side_of_line({1: ("a", "both", 0, "")})
    lists = G.port_lists(reg.seeds_table(EXP))
    assert lists[8292][0] == "1900" and lists[8293][0] == "1901"
